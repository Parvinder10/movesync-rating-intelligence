NEGATIVE_WORDS = set([
    "worst", "bad", "horrible", "pathetic", "useless", "terrible", "waste", "poor", "hate",
    "irritating", "annoying", "disaster", "ridiculous", "rubbish", "slow", "fail", "failed",
    "broken", "never", "fool", "fools", "bekar", "ghatiya", "bogus"
])


class ReviewClassifier:
    @classmethod
    def compute_sentiment(cls, text: str, score: int) -> Tuple[str, float]:
        """
        Determines sentiment label and continuous score (-1.0 to 1.0).
        Blends star rating with lexical analysis.
        """
        lower = text.lower()
        words = re.findall(r"\b\w+\b", lower)

        pos_count = sum(1 for w in words if w in POSITIVE_WORDS)
        neg_count = sum(1 for w in words if w in NEGATIVE_WORDS)

        # Star score normalized from [1..5] to [-1..1]
        score_norm = (score - 3) / 2.0

        lex_norm = 0.0
        if pos_count + neg_count > 0:
            lex_norm = (pos_count - neg_count) / (pos_count + neg_count)

        # 60% star weight, 40% lexical weight
        combined = 0.6 * score_norm + 0.4 * lex_norm
        combined = max(-1.0, min(1.0, round(combined, 3)))

        if combined > 0.15:
            sentiment = "positive"
        elif combined < -0.15:
            sentiment = "negative"
        else:
            sentiment = "neutral"

        return sentiment, combined

    @classmethod
    def classify_review(cls, text: str, score: int) -> Tuple[str, Optional[str], List[str]]:
        """
        Matches text against THEME_TAXONOMY keywords.
        Returns (primary_theme, secondary_theme, matched_keywords).
        """
        lower = text.lower()
        scores = {}
        matched_kw_map = {}

        for theme_code, meta in THEME_TAXONOMY.items():
            if theme_code == "POSITIVE_EXPERIENCE" and score <= 2:
                continue # Ignore positive theme for 1-2 star reviews

            matches = []
            for kw in meta["keywords"]:
                # Check keyword match
                pattern = r"\b" + re.escape(kw) + r"\b"
                if re.search(pattern, lower):
                    matches.append(kw)

            if matches:
                scores[theme_code] = len(matches)
                matched_kw_map[theme_code] = matches

        if not scores:
            if score >= 4:
                return "POSITIVE_EXPERIENCE", None, []
            elif score <= 2:
                # General critical feedback if no specific keyword detected
                return "GENERAL_DISSATISFACTION", None, []
            else:
                return "NEUTRAL_GENERAL", None, []

        sorted_themes = sorted(scores.items(), key=lambda x: x[1], reverse=True)
        primary = sorted_themes[0][0]
        secondary = sorted_themes[1][0] if len(sorted_themes) > 1 else None
        matched_kws = matched_kw_map.get(primary, [])

        return primary, secondary, matched_kws

    @classmethod
    def process_review(cls, clean_record: Dict[str, Any]) -> Dict[str, Any]:
        """Enriches cleaned review record with sentiment and theme classifications."""
        text = clean_record["cleaned_content"]
        score = clean_record["score"]

        sentiment, sentiment_score = cls.compute_sentiment(text, score)
        primary_theme, secondary_theme, matched_kws = cls.classify_review(text, score)

        enriched = dict(clean_record)
        enriched["sentiment"] = sentiment
        enriched["sentiment_score"] = sentiment_score
        enriched["primary_theme"] = primary_theme
        enriched["secondary_theme"] = secondary_theme
        enriched["matched_keywords"] = matched_kws
        return enriched
